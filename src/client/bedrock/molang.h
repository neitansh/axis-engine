#pragma once

#include "irrTypes.h"
#include <string>
#include <memory>
#include <vector>

/*
 * Молang — язык выражений Bedrock. Blockbench позволяет написать выражение
 * вместо числа прямо в ключе анимации, и авторы этим пользуются: покачивание
 * ствола или вращение барабана короче записать формулой, чем полусотней
 * ключей.
 *
 * Целиком язык нам не нужен и вреден: в нём есть переменные, присваивания,
 * ветвления и запросы к состоянию мира, а на стороне клиента, где крутится
 * анимация, ничего этого не существует. Поддерживается то, что действительно
 * встречается в анимациях: арифметика, скобки, функции Math.* и время самой
 * анимации. Всё остальное честно превращается в ноль и попадает в журнал —
 * молча подставлять правдоподобное число хуже, чем показать, что не понято.
 *
 * Важная тонкость: тригонометрия здесь в ГРАДУСАХ, как и во всём Bedrock.
 */

namespace bedrock
{

/// Разобранное выражение. Дешёвое в вычислении: разбор происходит один раз,
/// при загрузке модели, дерево остаётся жить в анимации.
class Molang
{
public:
	struct Node;

	/// Разобрать выражение. Пустая строка и мусор дают выражение-ноль.
	static Molang parse(const std::string &source);

	/// Постоянное выражение — просто число. Такие не нужно семплировать.
	static Molang constant(f32 value);

	/// @param anim_time секунд с начала проигрывания анимации
	f32 eval(f32 anim_time) const;

	/// Зависит ли выражение от времени. Если нет, кривую можно не дробить.
	bool isConstant() const { return m_constant; }

	f32 constantValue() const { return m_value; }

private:
	std::shared_ptr<Node> m_root;
	bool m_constant = true;
	f32 m_value = 0.0f;
};

} // namespace bedrock

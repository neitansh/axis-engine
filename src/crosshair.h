#pragma once

#include "irrlichttypes_bloated.h"
#include <string>
#include <vector>

class Settings;

/*!
 * Перекрестье: как оно устроено и как его рисовать.
 *
 * Перекрестье — единственная часть картинки, на которую игрок смотрит всё
 * время, и вкус тут у каждого свой: кому точку, кому четыре штриха с
 * просветом, кому рамку. Раздавать это картинками неудобно — под каждый вкус
 * пришлось бы держать файл, — поэтому перекрестье собирается из прямоугольников
 * по описанию: форма, длина штриха, толщина, просвет, точка, обводка, цвет.
 *
 * Геометрия живёт здесь, в одном месте, и её спрашивают двое: HUD, который
 * рисует настоящее перекрестье, и меню настроек, которое показывает
 * предпросмотр. Считать её дважды нельзя — разойдутся.
 */
struct CrosshairStyle
{
	//! Из чего складывается перекрестье.
	enum Shape : u8
	{
		//! Четыре штриха крестом. Просвет посередине — по вкусу.
		SHAPE_CROSS = 0,
		//! Те же четыре штриха, но по диагоналям.
		SHAPE_X,
		//! Только точка. Меньше всего закрывает цель.
		SHAPE_DOT,
		//! Кольцо.
		SHAPE_CIRCLE,
		//! Рамка.
		SHAPE_SQUARE,
		//! Четыре уголка — «скобки» вокруг цели.
		SHAPE_BRACKETS,
		//! Ничего. Стрелять по памяти.
		SHAPE_NONE,
		SHAPE_COUNT
	};

	Shape shape = SHAPE_CROSS;

	//! Длина штриха (у кольца и рамки — половина размера), в пикселях.
	s32 size = 6;
	//! Толщина линии, в пикселях.
	s32 thickness = 2;
	//! Просвет от центра до начала штриха, в пикселях.
	s32 gap = 3;
	//! Сторона точки в центре; ноль — без точки.
	s32 dot = 0;
	//! Толщина тёмной обводки вокруг всего; ноль — без обводки.
	s32 outline = 1;

	video::SColor color{255, 255, 255, 255};
	video::SColor outline_color{160, 0, 0, 0};
	//! Цвет, когда прицел наведён на кого-то живого.
	video::SColor object_color{255, 255, 80, 80};

	//! Прямоугольник в пикселях относительно центра экрана.
	struct Piece
	{
		s32 x, y, w, h;
	};

	/*!
	 * Разложить перекрестье на прямоугольники.
	 *
	 * \param scale масштаб интерфейса: на большом экране перекрестье
	 *        растёт вместе со всем остальным
	 */
	std::vector<Piece> pieces(f32 scale = 1.0f) const;

	/*!
	 * То же, но обводка: те же куски, раздутые на её толщину.
	 *
	 * Рисуется первой, под самим перекрестьем. Без неё белые штрихи теряются
	 * на снегу и в небе — а именно туда чаще всего и целятся.
	 */
	std::vector<Piece> outlinePieces(f32 scale = 1.0f) const;

	//! Прочитать из настроек.
	static CrosshairStyle fromSettings(Settings *settings);

	//! Записать в настройки.
	void toSettings(Settings *settings) const;

	/*!
	 * Строка, которой делятся.
	 *
	 * Вид: `AXCH1-cross-6-2-3-0-1-ffffffff-a0000000-ffff5050`. Человек её
	 * прочитает, а главное — перешлёт в чат, и там она не рассыплется: ни
	 * пробелов, ни запятых, ни того, что съедает разметка.
	 */
	std::string toCode() const;

	/*!
	 * Разобрать такую строку.
	 *
	 * Чужой строке не верим ни в чём: неизвестная версия, лишние поля,
	 * запредельные числа — отказ, а не «поправим и возьмём». Испорченное
	 * перекрестье — это не косметика, это невозможность целиться.
	 *
	 * \return получилось ли; при отказе стиль не изменён
	 */
	static bool fromCode(const std::string &code, CrosshairStyle &out);

	//! Имя формы для настроек и кода.
	static const char *shapeName(Shape shape);
	//! Форма по имени; SHAPE_COUNT, если имя чужое.
	static Shape shapeByName(const std::string &name);

	//! Пределы: за ними перекрестье перестаёт быть перекрестьем.
	static constexpr s32 MAX_SIZE = 32;
	static constexpr s32 MAX_THICKNESS = 8;
	static constexpr s32 MAX_GAP = 24;
	static constexpr s32 MAX_DOT = 8;
	static constexpr s32 MAX_OUTLINE = 3;
};

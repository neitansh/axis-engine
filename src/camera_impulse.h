#pragma once

#include "irrlichttypes_bloated.h"

/*
	Толчок камере — то, что сервер посылает, а клиент доигрывает сам
	(src/client/camera_fx.h).

	Здесь только содержимое пакета: сервер про пружины ничего не знает и
	знать не должен. Он говорит «случилось вот такое событие вот такой силы»,
	а как это выглядит и сколько затухает, решает клиент — иначе плавность
	упёрлась бы в частоту серверного тика.
*/
struct CameraImpulse
{
	enum Kind : u8
	{
		// Отдача оружия: вращательная пружина.
		RECOIL = 0,
		// Удар взрывной волны: вращательная и линейная разом.
		BLAST = 1,
		// Дрожь: затухающие колебания.
		SHAKE = 2,
		// Снять всё разом — на возрождении.
		RESET = 3,
	};

	Kind kind = RECOIL;

	// Оси как у обзора игрока: X — pitch (плюс вниз), Y — yaw (плюс против
	// часовой), Z — крен. Радианы в секунду: это скорость, а не угол, —
	// пружина сама решает, до какого угла её раскачает.
	v3f rotation;
	// Линейный толчок в горизонтальной системе игрока: X вправо, Y вверх,
	// Z вперёд. Ноды в секунду.
	v3f position;
	// Характер возврата. У каждого оружия свой, поэтому едет вместе с
	// импульсом, а не живёт константой в клиенте.
	f32 stiffness = 90.0f;
	f32 damping = 19.0f;

	// Только для SHAKE.
	f32 amplitude = 0.0f; // рад
	f32 frequency = 0.0f; // Гц
	f32 decay = 0.0f;     // 1/с
	f32 duration = 0.0f;  // с
};

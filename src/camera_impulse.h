#pragma once

#include "irrlichttypes_bloated.h"

/*
	Толчок камере — то, что сервер посылает, а клиент доигрывает сам
	(src/client/camera_fx.h).

	Здесь только содержимое пакета: сервер про пружины ничего не знает и
	знать не должен. Он говорит «толкнуть вот так и вот с такой силой», а как
	это выглядит и сколько затухает, решает клиент — иначе плавность упёрлась
	бы в частоту серверного тика.

	Виды названы по тому, что они делают с камерой, а не по игровому событию.
	Стреляют не во всякой игре, а качнуть обзор хочется и от землетрясения, и
	от посадки корабля, и от упавшего рядом дерева; движку незачем знать, что
	именно случилось. Своё событие игра называет сама, поверх этих видов.
*/
struct CameraImpulse
{
	enum Kind : u8
	{
		// Вращательная пружина: угол обзора уводит и возвращает.
		ROTATE = 0,
		// Вращательная и линейная разом: уводит и угол, и сами глаза.
		PUSH = 1,
		// Затухающие колебания.
		OSCILLATE = 2,
		// Снять всё разом.
		CLEAR = 3,
	};

	Kind kind = ROTATE;

	// Оси как у обзора игрока: X — pitch (плюс вниз), Y — yaw (плюс против
	// часовой), Z — крен. Радианы в секунду: это скорость, а не угол, —
	// пружина сама решает, до какого угла её раскачает.
	v3f rotation;
	// Линейный толчок в горизонтальной системе игрока: X вправо, Y вверх,
	// Z вперёд. Ноды в секунду.
	v3f position;
	// Характер возврата. У каждого источника толчка свой, поэтому едет вместе
	// с импульсом, а не живёт константой в клиенте.
	f32 stiffness = 90.0f;
	f32 damping = 19.0f;

	// Только для OSCILLATE.
	f32 amplitude = 0.0f; // рад
	f32 frequency = 0.0f; // Гц
	f32 decay = 0.0f;     // 1/с
	f32 duration = 0.0f;  // с
};
